--COMPRAS: calcula el subtotal de cada linea
CREATE OR REPLACE TRIGGER TRG_BIR_DET_COMPRA_SUBTOTAL
BEFORE INSERT ON DETALLE_COMPRA
FOR EACH ROW
BEGIN
  :NEW.SUBTOTAL := :NEW.CANTIDAD * :NEW.COSTO_UNITARIO;
END;
/

--OMPRAS: al pasar a RECIBIDA se suma el inventario y se registra el movimiento
CREATE OR REPLACE TRIGGER TRG_AUR_COMPRA_RECIBIDA
AFTER UPDATE OF ESTADO ON COMPRA
FOR EACH ROW
BEGIN
  IF :OLD.ESTADO = 'RECIBIDA' AND :NEW.ESTADO <> 'RECIBIDA' THEN
    RAISE_APPLICATION_ERROR(-20007, 'Una compra recibida no se puede cambiar de estado.');
  END IF;

  IF :OLD.ESTADO <> 'RECIBIDA' AND :NEW.ESTADO = 'RECIBIDA' THEN
    FOR R IN (SELECT ID_PRODUCTO, CANTIDAD FROM DETALLE_COMPRA WHERE ID_COMPRA = :NEW.ID_COMPRA) LOOP
      UPDATE INVENTARIO
         SET EXISTENCIA = EXISTENCIA + R.CANTIDAD,
             FECHA_ACTUALIZACION = SYSDATE
       WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
         AND ID_PRODUCTO = R.ID_PRODUCTO;

      IF SQL%ROWCOUNT = 0 THEN
        INSERT INTO INVENTARIO (ID_SUCURSAL, ID_PRODUCTO, EXISTENCIA)
        VALUES (:NEW.ID_SUCURSAL, R.ID_PRODUCTO, R.CANTIDAD);
      END IF;

      PRC_REGISTRA_MOV_INVENTARIO(:NEW.ID_SUCURSAL, R.ID_PRODUCTO, 'COMPRA', R.CANTIDAD, 'COMPRA', :NEW.ID_COMPRA, 'Compra recibida');
    END LOOP;
  END IF;
END;
/

--NOTA DE CREDITO: valida la cantidad y toma el precio de la factura
CREATE OR REPLACE TRIGGER TRG_BIR_DET_NC_VALIDA
BEFORE INSERT ON DETALLE_NOTA_CREDITO
FOR EACH ROW
DECLARE
  V_CANTIDAD NUMBER;
  V_PRECIO NUMBER;
BEGIN
  BEGIN
    SELECT CANTIDAD, PRECIO_UNITARIO INTO V_CANTIDAD, V_PRECIO
    FROM DETALLE_FACTURA
    WHERE ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20008, 'La linea de factura con ID ' || :NEW.ID_DETALLE_FACTURA || ' no existe.');
  END;

  IF :NEW.CANTIDAD > V_CANTIDAD THEN
    RAISE_APPLICATION_ERROR(-20009, 'La cantidad a devolver supera la cantidad facturada (' || V_CANTIDAD || ').');
  END IF;

  :NEW.PRECIO_UNITARIO := V_PRECIO;
  :NEW.SUBTOTAL := :NEW.CANTIDAD * V_PRECIO;
END;
/

--NOTA DE CREDITO: si el producto reingresa, se devuelve al inventario
CREATE OR REPLACE TRIGGER TRG_AIR_DET_NC_REINGRESO
AFTER INSERT ON DETALLE_NOTA_CREDITO
FOR EACH ROW
DECLARE
  V_SUCURSAL NUMBER;
  V_PRODUCTO NUMBER;
BEGIN
  IF :NEW.REINGRESA_INVENTARIO = 'S' THEN
    SELECT F.ID_SUCURSAL, D.ID_PRODUCTO INTO V_SUCURSAL, V_PRODUCTO
    FROM DETALLE_FACTURA D
    JOIN FACTURA F ON F.ID_FACTURA = D.ID_FACTURA
    WHERE D.ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA;

    UPDATE INVENTARIO
       SET EXISTENCIA = EXISTENCIA + :NEW.CANTIDAD,
           FECHA_ACTUALIZACION = SYSDATE
     WHERE ID_SUCURSAL = V_SUCURSAL
       AND ID_PRODUCTO = V_PRODUCTO;

    PRC_REGISTRA_MOV_INVENTARIO(V_SUCURSAL, V_PRODUCTO, 'DEVOLUCION', :NEW.CANTIDAD, 'NOTA_CREDITO', :NEW.ID_NOTA_CREDITO, 'Devolucion por nota de credito');
  END IF;
END;
/

-- RECLAMO DE GARANTIA: valida que la garantia este vigente
CREATE OR REPLACE TRIGGER TRG_BIR_RECLAMO_VALIDA
BEFORE INSERT ON RECLAMO_GARANTIA
FOR EACH ROW
DECLARE
  V_INICIO DATE;
  V_FIN DATE;
  V_CUBIERTA NUMBER;
BEGIN
  :NEW.FECHA_RECLAMO := NVL(:NEW.FECHA_RECLAMO, SYSDATE);

  BEGIN
    SELECT FECHA_INICIO, FECHA_FIN, CANTIDAD_CUBIERTA INTO V_INICIO, V_FIN, V_CUBIERTA
    FROM GARANTIA
    WHERE ID_GARANTIA = :NEW.ID_GARANTIA;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20010, 'La garantia con ID ' || :NEW.ID_GARANTIA || ' no existe.');
  END;

  IF TRUNC(:NEW.FECHA_RECLAMO) < V_INICIO OR TRUNC(:NEW.FECHA_RECLAMO) > V_FIN THEN
    RAISE_APPLICATION_ERROR(-20011, 'La garantia no esta vigente. Cobertura: ' || TO_CHAR(V_INICIO, 'DD/MM/YYYY') || ' al ' || TO_CHAR(V_FIN, 'DD/MM/YYYY'));
  END IF;

  IF :NEW.CANTIDAD_RECLAMADA > V_CUBIERTA THEN
    RAISE_APPLICATION_ERROR(-20012, 'La cantidad reclamada supera la cantidad cubierta (' || V_CUBIERTA || ').');
  END IF;
END;
/

--RECLAMO DE GARANTIA: si se cierra como CAMBIO, descuenta el producto de reemplazo
CREATE OR REPLACE TRIGGER TRG_AUR_RECLAMO_CAMBIO
AFTER UPDATE ON RECLAMO_GARANTIA
FOR EACH ROW
DECLARE
  V_EXISTENCIA NUMBER;
BEGIN
  IF :NEW.TIPO_RESOLUCION = 'CAMBIO' AND :NEW.ESTADO = 'CERRADO' AND :OLD.ESTADO <> 'CERRADO' THEN
    IF :NEW.ID_PRODUCTO_REEMPLAZO IS NULL THEN
      RAISE_APPLICATION_ERROR(-20013, 'Debe indicar el producto de reemplazo para un cambio.');
    END IF;

    BEGIN
      SELECT EXISTENCIA INTO V_EXISTENCIA
      FROM INVENTARIO
      WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
        AND ID_PRODUCTO = :NEW.ID_PRODUCTO_REEMPLAZO;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20014, 'El producto de reemplazo no tiene inventario en la sucursal.');
    END;

    IF V_EXISTENCIA >= :NEW.CANTIDAD_APROBADA THEN
      UPDATE INVENTARIO
         SET EXISTENCIA = EXISTENCIA - :NEW.CANTIDAD_APROBADA,
             FECHA_ACTUALIZACION = SYSDATE
       WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
         AND ID_PRODUCTO = :NEW.ID_PRODUCTO_REEMPLAZO;

      PRC_REGISTRA_MOV_INVENTARIO(:NEW.ID_SUCURSAL, :NEW.ID_PRODUCTO_REEMPLAZO, 'CAMBIO', :NEW.CANTIDAD_APROBADA, 'RECLAMO_GARANTIA', :NEW.ID_RECLAMO, 'Cambio por garantia');
    ELSE
      RAISE_APPLICATION_ERROR(-20015, 'No hay existencia suficiente del producto de reemplazo. Disponible: ' || V_EXISTENCIA);
    END IF;
  END IF;
END;
/

