--PROCEDIMIENTO QUE REGISTRA EL MOVIMIENTO DE INVENTARIO
CREATE OR REPLACE PROCEDURE PRC_REGISTRA_MOV_INVENTARIO
(
  P_ID_SUCURSAL IN NUMBER,
  P_ID_PRODUCTO IN NUMBER,
  P_TIPO_MOVIMIENTO IN VARCHAR2,
  P_CANTIDAD IN NUMBER,
  P_TIPO_ORIGEN IN VARCHAR2,
  P_ID_ORIGEN IN NUMBER,
  P_JUSTIFICACION IN VARCHAR2
) IS
BEGIN
  INSERT INTO MOVIMIENTO_INVENTARIO (ID_SUCURSAL, ID_PRODUCTO, TIPO_MOVIMIENTO, CANTIDAD, TIPO_ORIGEN, ID_ORIGEN, JUSTIFICACION)
  VALUES (P_ID_SUCURSAL, P_ID_PRODUCTO, P_TIPO_MOVIMIENTO, P_CANTIDAD, P_TIPO_ORIGEN, P_ID_ORIGEN, P_JUSTIFICACION);
END;
/

--FACTURACION: valida existencia, descuenta inventario y toma el precio del producto
CREATE OR REPLACE TRIGGER TRG_BIR_DETALLE_FACTURA_STOCK
BEFORE INSERT ON DETALLE_FACTURA
FOR EACH ROW
DECLARE
  V_SUCURSAL NUMBER;
  V_EXISTENCIA NUMBER;
  V_PRECIO NUMBER;
BEGIN
  BEGIN
    SELECT PRECIO_VENTA INTO V_PRECIO
    FROM PRODUCTO
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20002, 'El producto con ID ' || :NEW.ID_PRODUCTO || ' no existe.');
  END;

  BEGIN
    SELECT ID_SUCURSAL INTO V_SUCURSAL
    FROM FACTURA
    WHERE ID_FACTURA = :NEW.ID_FACTURA;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20003, 'La factura con ID ' || :NEW.ID_FACTURA || ' no existe.');
  END;

  BEGIN
    SELECT EXISTENCIA INTO V_EXISTENCIA
    FROM INVENTARIO
    WHERE ID_SUCURSAL = V_SUCURSAL
      AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20004, 'El producto con ID ' || :NEW.ID_PRODUCTO || ' no tiene inventario en la sucursal.');
  END;

  IF V_EXISTENCIA >= :NEW.CANTIDAD THEN
    UPDATE INVENTARIO
       SET EXISTENCIA = EXISTENCIA - :NEW.CANTIDAD,
           FECHA_ACTUALIZACION = SYSDATE
     WHERE ID_SUCURSAL = V_SUCURSAL
       AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
    :NEW.PRECIO_UNITARIO := V_PRECIO;
    :NEW.DESCUENTO := NVL(:NEW.DESCUENTO, 0);
    :NEW.SUBTOTAL := (:NEW.CANTIDAD * V_PRECIO) - :NEW.DESCUENTO;
  ELSE
    RAISE_APPLICATION_ERROR(-20001, 'NO HAY EXISTENCIA SUFICIENTE PARA EFECTUAR LA VENTA. Disponible: ' || V_EXISTENCIA);
  END IF;
END;
/

--FACTURACION: registra el movimiento de inventario (salida por venta)
CREATE OR REPLACE TRIGGER TRG_AIR_DETALLE_FACTURA
AFTER INSERT ON DETALLE_FACTURA
FOR EACH ROW
DECLARE
  V_SUCURSAL NUMBER;
BEGIN
  SELECT ID_SUCURSAL INTO V_SUCURSAL
  FROM FACTURA
  WHERE ID_FACTURA = :NEW.ID_FACTURA;

  PRC_REGISTRA_MOV_INVENTARIO(V_SUCURSAL, :NEW.ID_PRODUCTO, 'VENTA', :NEW.CANTIDAD, 'FACTURA', :NEW.ID_FACTURA, 'Venta por factura');
EXCEPTION
  WHEN OTHERS THEN
    RAISE_APPLICATION_ERROR(-20005, 'Error al registrar el movimiento del inventario ' || :NEW.ID_PRODUCTO || ' * ' || SQLERRM);
END;
/

--GARANTIA: se crea automaticamente si el producto tiene meses de garantia
CREATE OR REPLACE TRIGGER TRG_AIR_GARANTIA_FACTURA
AFTER INSERT ON DETALLE_FACTURA
FOR EACH ROW
DECLARE
  V_MESES NUMBER;
  V_FECHA DATE;
BEGIN
  SELECT MESES_GARANTIA INTO V_MESES
  FROM PRODUCTO
  WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

  IF V_MESES > 0 THEN
    SELECT FECHA INTO V_FECHA
    FROM FACTURA
    WHERE ID_FACTURA = :NEW.ID_FACTURA;

    INSERT INTO GARANTIA (ID_DETALLE_FACTURA, FECHA_INICIO, FECHA_FIN, CANTIDAD_CUBIERTA)
    VALUES (:NEW.ID_DETALLE_FACTURA, TRUNC(V_FECHA), ADD_MONTHS(TRUNC(V_FECHA), V_MESES), :NEW.CANTIDAD);
  END IF;
END;
/

