  ID_RECLAMO NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_GARANTIA NUMBER NOT NULL,
  ID_SUCURSAL NUMBER NOT NULL,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_PRODUCTO_REEMPLAZO NUMBER,
  FECHA_RECLAMO DATE DEFAULT SYSDATE NOT NULL,
  DESCRIPCION_FALLA VARCHAR2(250) NOT NULL,
  CANTIDAD_RECLAMADA NUMBER(8) NOT NULL,
  CANTIDAD_APROBADA NUMBER(8) DEFAULT 0 NOT NULL,
  TIPO_RESOLUCION VARCHAR2(20),
  ESTADO VARCHAR2(20) DEFAULT 'RECIBIDO' NOT NULL,
  FECHA_CREACION DATE DEFAULT SYSDATE,
  CREADO_POR VARCHAR2(30) DEFAULT USER,
  FECHA_MODIFICACION DATE,
  MODIFICADO_POR VARCHAR2(30),
  CONSTRAINT PK_RECLAMO_GARANTIA PRIMARY KEY (ID_RECLAMO),
  CONSTRAINT FK_RG_GARANTIA FOREIGN KEY (ID_GARANTIA) REFERENCES GARANTIA (ID_GARANTIA),
  CONSTRAINT FK_RG_SUCURSAL FOREIGN KEY (ID_SUCURSAL) REFERENCES SUCURSAL (ID_SUCURSAL),
  CONSTRAINT FK_RG_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO (ID_EMPLEADO),
  CONSTRAINT FK_RG_PRODUCTO_REEMPLAZO FOREIGN KEY (ID_PRODUCTO_REEMPLAZO) REFERENCES PRODUCTO (ID_PRODUCTO),
  CONSTRAINT CK_RG_RESOLUCION CHECK (TIPO_RESOLUCION IN ('REPARACION','CAMBIO','RECHAZADO')),
  CONSTRAINT CK_RG_ESTADO CHECK (ESTADO IN ('RECIBIDO','EN_PROCESO','CERRADO'))
);

CREATE TABLE ROL
(
  ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE VARCHAR2(50) NOT NULL,
  DESCRIPCION VARCHAR2(150),
  FECHA_CREACION DATE DEFAULT SYSDATE,
  CREADO_POR VARCHAR2(30) DEFAULT USER,
  FECHA_MODIFICACION DATE,
  MODIFICADO_POR VARCHAR2(30),
  CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL),
  CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIO
(
  ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_EMPLEADO NUMBER NOT NULL,
  ID_ROL NUMBER NOT NULL,
  USERNAME VARCHAR2(50) NOT NULL,
  PASSWORD_HASH VARCHAR2(255) NOT NULL,
  INTENTOS_FALLIDOS NUMBER(2) DEFAULT 0 NOT NULL,
  ULTIMO_ACCESO DATE,
  ESTADO VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
  FECHA_CREACION DATE DEFAULT SYSDATE,
  CREADO_POR VARCHAR2(30) DEFAULT USER,
  FECHA_MODIFICACION DATE,
  MODIFICADO_POR VARCHAR2(30),
  CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
  CONSTRAINT FK_USUARIO_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO (ID_EMPLEADO),
  CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL (ID_ROL),
  CONSTRAINT UQ_USUARIO_EMPLEADO UNIQUE (ID_EMPLEADO),
  CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME),
  CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE MENU
(
  ID_MENU NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_MENU_PADRE NUMBER,
  NOMBRE_OPCION VARCHAR2(100) NOT NULL,
  URL_PANTALLA VARCHAR2(150),
  ICONO VARCHAR2(50),
  ORDEN NUMBER(3) DEFAULT 1 NOT NULL,
  FECHA_CREACION DATE DEFAULT SYSDATE,
  CREADO_POR VARCHAR2(30) DEFAULT USER,
  FECHA_MODIFICACION DATE,
  MODIFICADO_POR VARCHAR2(30),
  CONSTRAINT PK_MENU PRIMARY KEY (ID_MENU),
  CONSTRAINT FK_MENU_PADRE FOREIGN KEY (ID_MENU_PADRE) REFERENCES MENU (ID_MENU),
  CONSTRAINT UQ_MENU_NOMBRE UNIQUE (NOMBRE_OPCION)
);

CREATE TABLE ROL_MENU
(
  ID_ROL_MENU NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_ROL NUMBER NOT NULL,
  ID_MENU NUMBER NOT NULL,
  PERMISO_LECTURA CHAR(1) DEFAULT 'S' NOT NULL,
  PERMISO_ESCRITURA CHAR(1) DEFAULT 'N' NOT NULL,
  PERMISO_EDICION CHAR(1) DEFAULT 'N' NOT NULL,
  PERMISO_ELIMINACION CHAR(1) DEFAULT 'N' NOT NULL,
  FECHA_CREACION DATE DEFAULT SYSDATE,
  CREADO_POR VARCHAR2(30) DEFAULT USER,
  FECHA_MODIFICACION DATE,
  MODIFICADO_POR VARCHAR2(30),
  CONSTRAINT PK_ROL_MENU PRIMARY KEY (ID_ROL_MENU),
  CONSTRAINT FK_ROLMENU_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL (ID_ROL),
  CONSTRAINT FK_ROLMENU_MENU FOREIGN KEY (ID_MENU) REFERENCES MENU (ID_MENU),
  CONSTRAINT UQ_ROLMENU_ROL_MENU UNIQUE (ID_ROL, ID_MENU),
  CONSTRAINT CK_RM_LECTURA CHECK (PERMISO_LECTURA IN ('S','N')),
  CONSTRAINT CK_RM_ESCRITURA CHECK (PERMISO_ESCRITURA IN ('S','N')),
  CONSTRAINT CK_RM_EDICION CHECK (PERMISO_EDICION IN ('S','N')),
  CONSTRAINT CK_RM_ELIMINACION CHECK (PERMISO_ELIMINACION IN ('S','N'))
);

CREATE TABLE BITACORA
(
  ID_BITACORA NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_USUARIO NUMBER,
  TABLA_AFECTADA VARCHAR2(50) NOT NULL,
  ACCION VARCHAR2(20) NOT NULL,
  FECHA DATE DEFAULT SYSDATE NOT NULL,
  VALOR_ANTERIOR VARCHAR2(4000),
  VALOR_NUEVO VARCHAR2(4000),
  CONSTRAINT PK_BITACORA PRIMARY KEY (ID_BITACORA),
  CONSTRAINT FK_BITACORA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT CK_BITACORA_ACCION CHECK (ACCION IN ('INSERT','UPDATE','DELETE'))
);





