CREATE OR REPLACE PACKAGE PKG_GARANTIAS IS
  FUNCTION VIGENTE (P_ID_GARANTIA IN NUMBER) RETURN VARCHAR2;
  FUNCTION DIAS_RESTANTES (P_ID_GARANTIA IN NUMBER) RETURN NUMBER;
  PROCEDURE CERRAR_RECLAMO (
    P_ID_RECLAMO IN NUMBER,
    P_TIPO_RESOLUCION IN VARCHAR2,
    P_CANTIDAD_APROBADA IN NUMBER,
    P_ID_PRODUCTO_REEMPLAZO IN NUMBER
  );
END PKG_GARANTIAS;
/

CREATE OR REPLACE PACKAGE BODY PKG_GARANTIAS IS

  -- Devuelve S si la garantia esta vigente hoy, N si no
  FUNCTION VIGENTE (P_ID_GARANTIA IN NUMBER) RETURN VARCHAR2 IS
    V_INICIO DATE;
    V_FIN DATE;
  BEGIN
    SELECT FECHA_INICIO, FECHA_FIN INTO V_INICIO, V_FIN
    FROM GARANTIA
    WHERE ID_GARANTIA = P_ID_GARANTIA;

    IF TRUNC(SYSDATE) BETWEEN V_INICIO AND V_FIN THEN
      RETURN 'S';
    ELSE
      RETURN 'N';
    END IF;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN 'N';
  END;

  -- Dias que le quedan a la garantia (0 si ya vencio)
  FUNCTION DIAS_RESTANTES (P_ID_GARANTIA IN NUMBER) RETURN NUMBER IS
    V_FIN DATE;
  BEGIN
    SELECT FECHA_FIN INTO V_FIN
    FROM GARANTIA
    WHERE ID_GARANTIA = P_ID_GARANTIA;

    IF V_FIN < TRUNC(SYSDATE) THEN
      RETURN 0;
    ELSE
      RETURN V_FIN - TRUNC(SYSDATE);
    END IF;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN 0;
  END;

  -- Cierra un reclamo con su resolucion (el trigger descuenta el reemplazo si es CAMBIO)
  PROCEDURE CERRAR_RECLAMO (
    P_ID_RECLAMO IN NUMBER,
    P_TIPO_RESOLUCION IN VARCHAR2,
    P_CANTIDAD_APROBADA IN NUMBER,
    P_ID_PRODUCTO_REEMPLAZO IN NUMBER
  ) IS
  BEGIN
    UPDATE RECLAMO_GARANTIA
       SET TIPO_RESOLUCION = P_TIPO_RESOLUCION,
           CANTIDAD_APROBADA = P_CANTIDAD_APROBADA,
           ID_PRODUCTO_REEMPLAZO = P_ID_PRODUCTO_REEMPLAZO,
           ESTADO = 'CERRADO'
     WHERE ID_RECLAMO = P_ID_RECLAMO;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20023, 'El reclamo con ID ' || P_ID_RECLAMO || ' no existe.');
    END IF;
  END;

END PKG_GARANTIAS;
