
-- Ventas por sucursal
CREATE OR REPLACE VIEW VW_VENTAS_SUCURSAL AS
SELECT S.ID_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       COUNT(F.ID_FACTURA) AS NUM_FACTURAS,
       NVL(SUM(F.TOTAL), 0) AS TOTAL_VENTAS
FROM SUCURSAL S
LEFT JOIN FACTURA F ON F.ID_SUCURSAL = S.ID_SUCURSAL
GROUP BY S.ID_SUCURSAL, S.NOMBRE;

-- Ventas por producto
CREATE OR REPLACE VIEW VW_VENTAS_PRODUCTO AS
SELECT P.ID_PRODUCTO,
       P.CODIGO,
       P.NOMBRE AS PRODUCTO,
       C.NOMBRE AS CATEGORIA,
       SUM(D.CANTIDAD) AS UNIDADES_VENDIDAS,
       SUM(D.SUBTOTAL) AS TOTAL_VENDIDO
FROM DETALLE_FACTURA D
JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
JOIN CATEGORIA_PRODUCTO C ON C.ID_CATEGORIA = P.ID_CATEGORIA
GROUP BY P.ID_PRODUCTO, P.CODIGO, P.NOMBRE, C.NOMBRE;

-- Ventas por categoria
CREATE OR REPLACE VIEW VW_VENTAS_CATEGORIA AS
SELECT C.ID_CATEGORIA,
       C.NOMBRE AS CATEGORIA,
       SUM(D.CANTIDAD) AS UNIDADES_VENDIDAS,
       SUM(D.SUBTOTAL) AS TOTAL_VENDIDO
FROM DETALLE_FACTURA D
JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
JOIN CATEGORIA_PRODUCTO C ON C.ID_CATEGORIA = P.ID_CATEGORIA
GROUP BY C.ID_CATEGORIA, C.NOMBRE;

-- Ventas por empleado
CREATE OR REPLACE VIEW VW_VENTAS_EMPLEADO AS
SELECT E.ID_EMPLEADO,
       E.NOMBRES || ' ' || E.APELLIDOS AS EMPLEADO,
       S.NOMBRE AS SUCURSAL,
       COUNT(F.ID_FACTURA) AS NUM_FACTURAS,
       SUM(F.TOTAL) AS TOTAL_VENTAS
FROM FACTURA F
JOIN EMPLEADO E ON E.ID_EMPLEADO = F.ID_EMPLEADO
JOIN SUCURSAL S ON S.ID_SUCURSAL = F.ID_SUCURSAL
GROUP BY E.ID_EMPLEADO, E.NOMBRES, E.APELLIDOS, S.NOMBRE;

-- Garantias con su estado de vigencia
CREATE OR REPLACE VIEW VW_GARANTIAS AS
SELECT G.ID_GARANTIA,
       F.SERIE,
       F.NUMERO,
       CL.NOMBRES AS CLIENTE,
       P.NOMBRE AS PRODUCTO,
       G.FECHA_INICIO,
       G.FECHA_FIN,
       G.CANTIDAD_CUBIERTA,
       CASE WHEN TRUNC(SYSDATE) BETWEEN G.FECHA_INICIO AND G.FECHA_FIN
            THEN 'VIGENTE' ELSE 'VENCIDA' END AS ESTADO_GARANTIA
FROM GARANTIA G
JOIN DETALLE_FACTURA D ON D.ID_DETALLE_FACTURA = G.ID_DETALLE_FACTURA
JOIN FACTURA F ON F.ID_FACTURA = D.ID_FACTURA
JOIN CLIENTE CL ON CL.ID_CLIENTE = F.ID_CLIENTE
JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO;

-- Reclamos de garantia (reparaciones y cambios)
CREATE OR REPLACE VIEW VW_RECLAMOS_GARANTIA AS
SELECT R.ID_RECLAMO,
       R.FECHA_RECLAMO,
       P.NOMBRE AS PRODUCTO,
       S.NOMBRE AS SUCURSAL,
       R.DESCRIPCION_FALLA,
       R.CANTIDAD_RECLAMADA,
       R.CANTIDAD_APROBADA,
       R.TIPO_RESOLUCION,
       R.ESTADO
FROM RECLAMO_GARANTIA R
JOIN GARANTIA G ON G.ID_GARANTIA = R.ID_GARANTIA
JOIN DETALLE_FACTURA D ON D.ID_DETALLE_FACTURA = G.ID_DETALLE_FACTURA
JOIN PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
JOIN SUCURSAL S ON S.ID_SUCURSAL = R.ID_SUCURSAL;

-- Inventario por sucursal con alerta de stock bajo
CREATE OR REPLACE VIEW VW_INVENTARIO_SUCURSAL AS
SELECT S.NOMBRE AS SUCURSAL,
       P.CODIGO,
       P.NOMBRE AS PRODUCTO,
       I.EXISTENCIA,
       I.STOCK_MINIMO,
       CASE WHEN I.EXISTENCIA <= I.STOCK_MINIMO THEN 'BAJO' ELSE 'NORMAL' END AS ESTADO_STOCK
FROM INVENTARIO I
JOIN SUCURSAL S ON S.ID_SUCURSAL = I.ID_SUCURSAL
JOIN PRODUCTO P ON P.ID_PRODUCTO = I.ID_PRODUCTO;

-- Menu y permisos de cada usuario (la aplicacion la consulta al iniciar sesion)
CREATE OR REPLACE VIEW VW_MENU_USUARIO AS
SELECT U.USERNAME,
       R.NOMBRE AS ROL,
       M.ID_MENU,
       M.ID_MENU_PADRE,
       M.NOMBRE_OPCION,
       M.URL_PANTALLA,
       M.ICONO,
       M.ORDEN,
       RM.PERMISO_LECTURA,
       RM.PERMISO_ESCRITURA,
       RM.PERMISO_EDICION,
       RM.PERMISO_ELIMINACION
FROM USUARIO U
JOIN ROL R ON R.ID_ROL = U.ID_ROL
JOIN ROL_MENU RM ON RM.ID_ROL = R.ID_ROL
JOIN MENU M ON M.ID_MENU = RM.ID_MENU
WHERE U.ESTADO = 'ACTIVO';


-- IVA (12%) contenido en un total que ya lo incluye
CREATE OR REPLACE FUNCTION FN_CALCULA_IVA (P_TOTAL IN NUMBER) RETURN NUMBER IS
BEGIN
  RETURN ROUND(P_TOTAL - (P_TOTAL / 1.12), 2);
END;
