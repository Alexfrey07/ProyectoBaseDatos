-- Existencia de un producto en una sucursal (0 si no tiene inventario)
CREATE OR REPLACE FUNCTION FN_EXISTENCIA (P_ID_SUCURSAL IN NUMBER, P_ID_PRODUCTO IN NUMBER) RETURN NUMBER IS
  V_EXISTENCIA NUMBER;
BEGIN
  SELECT EXISTENCIA INTO V_EXISTENCIA
  FROM INVENTARIO
  WHERE ID_SUCURSAL = P_ID_SUCURSAL
    AND ID_PRODUCTO = P_ID_PRODUCTO;
  RETURN V_EXISTENCIA;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN 0;
END;
/



-- Marca una compra como recibida (el trigger suma el inventario)
CREATE OR REPLACE PROCEDURE PRC_RECIBIR_COMPRA (P_ID_COMPRA IN NUMBER) IS
BEGIN
  UPDATE COMPRA
     SET ESTADO = 'RECIBIDA'
   WHERE ID_COMPRA = P_ID_COMPRA;

  IF SQL%ROWCOUNT = 0 THEN
    RAISE_APPLICATION_ERROR(-20020, 'La compra con ID ' || P_ID_COMPRA || ' no existe.');
  END IF;
END;
/

-- Ajusta la existencia a un valor nuevo y deja el movimiento registrado
CREATE OR REPLACE PROCEDURE PRC_AJUSTE_INVENTARIO
(
  P_ID_SUCURSAL IN NUMBER,
  P_ID_PRODUCTO IN NUMBER,
  P_NUEVA_EXISTENCIA IN NUMBER,
  P_JUSTIFICACION IN VARCHAR2
) IS
  V_ACTUAL NUMBER;
BEGIN
  IF P_NUEVA_EXISTENCIA < 0 THEN
    RAISE_APPLICATION_ERROR(-20021, 'La existencia no puede ser negativa.');
  END IF;

  BEGIN
    SELECT EXISTENCIA INTO V_ACTUAL
    FROM INVENTARIO
    WHERE ID_SUCURSAL = P_ID_SUCURSAL
      AND ID_PRODUCTO = P_ID_PRODUCTO;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20022, 'El producto no tiene inventario en la sucursal.');
  END;

  UPDATE INVENTARIO
     SET EXISTENCIA = P_NUEVA_EXISTENCIA,
         FECHA_ACTUALIZACION = SYSDATE
   WHERE ID_SUCURSAL = P_ID_SUCURSAL
     AND ID_PRODUCTO = P_ID_PRODUCTO;

  PRC_REGISTRA_MOV_INVENTARIO(P_ID_SUCURSAL, P_ID_PRODUCTO, 'AJUSTE', P_NUEVA_EXISTENCIA - V_ACTUAL, NULL, NULL, P_JUSTIFICACION);
END;
