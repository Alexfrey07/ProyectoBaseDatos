DROP TABLE BITACORA;

CREATE TABLE BITACORA
(
  IDBITACORA NUMBER GENERATED BY DEFAULT AS IDENTITY,
  FECHA_REGISTRO DATE DEFAULT SYSDATE,
  TABLA VARCHAR2(100),
  CAMPO VARCHAR2(50),
  LLAVE VARCHAR2(100),
  TIPO_MOVIMIENTO VARCHAR2(10),
  VALOR_ANTERIOR VARCHAR2(4000),
  VALOR_NUEVO VARCHAR2(4000),
  CREADO_POR VARCHAR2(4000),
  IP VARCHAR2(50),
  NOMBRE_EQUIPO VARCHAR2(50),
  CONSTRAINT PK_BITACORA PRIMARY KEY (IDBITACORA)
);

-- PROCEDIMIENTO QUE REGISTRA EN BITACORA
CREATE OR REPLACE PROCEDURE PRC_BITACORA
(
  P_TABLA IN VARCHAR2,
  P_CAMPO IN VARCHAR2,
  P_TIPO_MOVIMIENTO IN VARCHAR2,
  P_VALOR_ANTERIOR IN VARCHAR2,
  P_VALOR_NUEVO IN VARCHAR2,
  P_LLAVE IN VARCHAR2
) IS
PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  INSERT INTO BITACORA (TABLA, CAMPO, TIPO_MOVIMIENTO, VALOR_ANTERIOR, VALOR_NUEVO, CREADO_POR, IP, NOMBRE_EQUIPO, LLAVE)
  VALUES (P_TABLA, P_CAMPO, P_TIPO_MOVIMIENTO, P_VALOR_ANTERIOR, P_VALOR_NUEVO,
          SYS_CONTEXT('USERENV', 'SESSION_USER'),
          SYS_CONTEXT('USERENV', 'IP_ADDRESS'),
          SYS_CONTEXT('USERENV', 'HOST'),
          P_LLAVE);
  COMMIT;
END;
/

