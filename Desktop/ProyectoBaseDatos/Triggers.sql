--RIGGERS DE BITACORA
-- La bitacora se registra en la tabla donde ocurre el cambio (no en el trigger de la factura)

-- PRODUCTO: precio, costo y estado
CREATE OR REPLACE TRIGGER TRG_AUR_PRODUCTO
AFTER UPDATE ON PRODUCTO
FOR EACH ROW
BEGIN
  IF :OLD.PRECIO_VENTA <> :NEW.PRECIO_VENTA THEN
    PRC_BITACORA('PRODUCTO', 'PRECIO_VENTA', 'UPDATE', :OLD.PRECIO_VENTA, :NEW.PRECIO_VENTA, :NEW.ID_PRODUCTO);
  END IF;
  IF :OLD.COSTO <> :NEW.COSTO THEN
    PRC_BITACORA('PRODUCTO', 'COSTO', 'UPDATE', :OLD.COSTO, :NEW.COSTO, :NEW.ID_PRODUCTO);
  END IF;
  IF :OLD.ESTADO <> :NEW.ESTADO THEN
    PRC_BITACORA('PRODUCTO', 'ESTADO', 'UPDATE', :OLD.ESTADO, :NEW.ESTADO, :NEW.ID_PRODUCTO);
  END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_ADR_PRODUCTO
AFTER DELETE ON PRODUCTO
FOR EACH ROW
BEGIN
  PRC_BITACORA('PRODUCTO', 'REGISTRO', 'DELETE', :OLD.NOMBRE, NULL, :OLD.ID_PRODUCTO);
END;
/

-- INVENTARIO: existencia y stock minimo (aqui se refleja lo que descuentan las ventas)
CREATE OR REPLACE TRIGGER TRG_AUR_INVENTARIO
AFTER UPDATE ON INVENTARIO
FOR EACH ROW
BEGIN
  IF :OLD.EXISTENCIA <> :NEW.EXISTENCIA THEN
    PRC_BITACORA('INVENTARIO', 'EXISTENCIA', 'UPDATE', :OLD.EXISTENCIA, :NEW.EXISTENCIA, :NEW.ID_INVENTARIO);
  END IF;
  IF :OLD.STOCK_MINIMO <> :NEW.STOCK_MINIMO THEN
    PRC_BITACORA('INVENTARIO', 'STOCK_MINIMO', 'UPDATE', :OLD.STOCK_MINIMO, :NEW.STOCK_MINIMO, :NEW.ID_INVENTARIO);
  END IF;
END;
/

